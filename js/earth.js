export function paintLand(width) {
  const height = width / 2;
  const c = document.createElement('canvas');
  c.width = width;
  c.height = height;
  const g = c.getContext('2d');
  const X = (lon) => ((lon + 180) / 360) * width;
  const Y = (lat) => ((90 - lat) / 180) * height;
  const poly = (pts) => {
    g.beginPath();
    pts.forEach(([lon, lat], i) => (i ? g.lineTo(X(lon), Y(lat)) : g.moveTo(X(lon), Y(lat))));
    g.closePath();
    g.fill();
  };
  g.fillStyle = '#000';
  g.fillRect(0, 0, width, height);
  g.fillStyle = '#f00';
  LAND.forEach(poly);
  g.fillStyle = '#000';
  WATER.forEach(poly);
  // Lights are soft dots with a scatter of smaller towns around them, added on green only.
  g.globalCompositeOperation = 'lighter';
  const R = rng(31);
  const px = width / 2048;
  const dot = (x, y, r, a) => {
    const d = g.createRadialGradient(x, y, 0, x, y, r);
    d.addColorStop(0, `rgba(0,255,0,${a})`);
    d.addColorStop(1, 'rgba(0,255,0,0)');
    g.fillStyle = d;
    g.fillRect(x - r, y - r, r * 2, r * 2);
  };
  CITIES.forEach(([lon, lat, b]) => {
    const x = X(lon), y = Y(lat);
    dot(x, y, 3.4 * b * px + 1.2, Math.min(1, 0.85 * b));
    const towns = Math.round(10 * b);
    for (let i = 0; i < towns; i++) {
      const a = R() * 6.283, d = Math.pow(R(), 0.7) * 22 * px * (0.6 + b);
      dot(x + Math.cos(a) * d, y + Math.sin(a) * d, (0.8 + R() * 1.1) * px + 0.6, 0.22 + R() * 0.34);
    }
  });
  return c;
}

